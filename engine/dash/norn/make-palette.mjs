// The Norn palette: 32 fixed colours, ordered in ramps. The ONE source; writes palette.hex (lospec format, one RRGGBB per
// line) and palette.png (32 x 1, one pixel per colour, the quantiser input) + palette-x16.png (a 8 x 4 swatch board, 16 px
// cells, for people). Usage: node make-palette.mjs   (no deps; PNG via node:zlib)
import fs from 'node:fs';
import zlib from 'node:zlib';

// name, hex - the ramps run dark -> light. Night ramp = dark theme ground, day ramp = light theme ground (one palette,
// two grounds: DECIDED in NOTES). Thread colours (gold / aqua / leaf / ember / violet) are shared by both themes.
export const PALETTE = [
  ['void', '0b0e1a'], ['night', '151c30'], ['deep', '1f2b45'], ['slate', '2e3f5f'],
  ['dusk', '425a7d'], ['mist', '6380a0'], ['frost', '93aec6'], ['snow', 'd3e2ec'],
  ['well-deep', '0e2b30'], ['well', '17504f'], ['teal', '2a8075'], ['aqua', '52b8a0'],
  ['wellglow', '9eecc9'], ['bark-deep', '241a14'], ['bark', '433021'], ['wood', '6b4a30'],
  ['oak', '9c7048'], ['moss-deep', '34431c'], ['moss', '5a7a2c'], ['leaf', '94b44c'],
  ['gold-deep', '6e430f'], ['gold', 'b8801e'], ['thread', 'eec24a'], ['spark', 'fff0a8'],
  ['blood', '571a22'], ['rune', 'a5302e'], ['ember', 'e2683f'], ['weird', 'a0569a'],
  ['vellum', 'f7f0dc'], ['parchment', 'e9dcbc'], ['linen', 'c9b48c'], ['ink', '8c7656'],
];

const crcT = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
const crc = b => { let c = -1; for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8); return (c ^ -1) >>> 0; };
const chunk = (t, d) => { const l = Buffer.alloc(4); l.writeUInt32BE(d.length); const td = Buffer.concat([Buffer.from(t), d]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
export function png(w, h, rgbAt) {
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const [r, g, b] = rgbAt(x, y), o = y * (w * 3 + 1) + 1 + x * 3; raw[o] = r; raw[o + 1] = g; raw[o + 2] = b; }
  const ih = Buffer.alloc(13); ih.writeUInt32BE(w, 0); ih.writeUInt32BE(h, 4); ih[8] = 8; ih[9] = 2;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ih), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}
const rgb = h => [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}` || process.argv[1].endsWith('make-palette.mjs')) {
  const D = new URL('./', import.meta.url);
  fs.writeFileSync(new URL('palette.hex', D), PALETTE.map(p => p[1]).join('\n') + '\n');
  fs.writeFileSync(new URL('palette.png', D), png(32, 1, x => rgb(PALETTE[x][1])));
  fs.writeFileSync(new URL('palette-x16.png', D), png(128, 64, (x, y) => rgb(PALETTE[(y >> 4) * 8 + (x >> 4)][1])));
  fs.writeFileSync(new URL('palette.mjs', D), '// generated by make-palette.mjs - do not edit; edit PALETTE there\nexport const PALETTE = ' + JSON.stringify(PALETTE) + ';\n');
  console.log('palette', PALETTE.length);
}
